"""Cargo test driver — runs validation-agent-generated Rust integration test files via `cargo test`.

The validation agent writes a Rust integration test file like:
    mod validation_params;
    use validation_params::{get_validation_test_cases, TestCase};
    use spacetimedb_table::table_index::hash_index::HashIndex;

    #[test]
    fn test_hash_index_point_lookup() {
        let cases = get_validation_test_cases();
        for (i, tc) in cases.iter().enumerate() {
            // exercise the code using tc.inputs and tc.expected
        }
    }

The get_validation_test_cases helper is generated by the driver and reads
from the immutable params file. The validation agent cannot modify the expected values.

Story-level fields:
- `cargo_package`: crate directory relative to repo (e.g., "crates/table")
- `cargo_module_dir`: workspace root if different from repo root (optional)
"""

from __future__ import annotations

from pathlib import Path

from .base import CaseResult, Driver, DriverResult, Execution, map_run_result_to_cases

# Rust helper module that the validation agent's test files import, written into the target
# crate's tests/ directory alongside the validation agent's test file.
PARAMS_HELPER_TEMPLATE = """\
use serde::Deserialize;
use serde_json::Value;
use std::fs;

#[derive(Debug, Deserialize)]
struct ParamsFile {
    test_cases: Vec<RawTestCase>,
}

#[derive(Debug, Deserialize)]
struct RawTestCase {
    inputs: Value,
    expected: Value,
}

#[derive(Debug)]
pub struct TestCase {
    pub name: String,
    pub inputs: Value,
    pub expected: Value,
}

pub fn get_validation_test_cases() -> Vec<TestCase> {
    let path = std::env::var("VALIDATION_PARAMS")
        .expect("VALIDATION_PARAMS env var not set");
    let data = fs::read_to_string(&path)
        .unwrap_or_else(|e| panic!("failed to read params file {path}: {e}"));
    let params: ParamsFile = serde_json::from_str(&data)
        .unwrap_or_else(|e| panic!("failed to parse params file {path}: {e}"));
    params
        .test_cases
        .into_iter()
        .enumerate()
        .map(|(i, tc)| TestCase {
            name: format!("case_{i}"),
            inputs: tc.inputs,
            expected: tc.expected,
        })
        .collect()
}
"""


class CargoTestDriver(Driver):
    """Runs validation-agent-generated Rust integration test files via `cargo test`."""

    script_extension = "_test.rs"

    def execute_story(
        self,
        story: dict,
        scripts_dir: Path,
        logs_dir: Path,
        repo_dir: Path,
        timeout: int = 300,
        spec_settings: dict | None = None,
    ) -> DriverResult:
        from ..runners.rust import RustRunConfig, run

        sid = story["id"]
        test_cases = self._get_test_cases(story)
        result = DriverResult(story_id=sid)

        cargo_package = story.get("cargo_package", "")
        crate_dir = repo_dir / cargo_package if cargo_package else None

        if not cargo_package or not crate_dir or not crate_dir.exists():
            result.cases.append(
                CaseResult(
                    case_index=0,
                    passed=False,
                    reason=f"cargo_package '{cargo_package}' not found at {crate_dir}",
                    ran=Execution.no,
                )
            )
            return result

        script_path = self._get_script_path(story, scripts_dir)
        if not script_path.exists():
            result.cases.append(
                CaseResult(case_index=0, passed=False, reason="Test file not generated", ran=Execution.no)
            )
            return result

        if not test_cases:
            result.cases.append(CaseResult(case_index=0, passed=False, reason="No test cases", ran=Execution.no))
            return result

        params_path = self.write_params_file(test_cases, logs_dir, sid)
        helper_path = logs_dir / "validation_params.rs"
        helper_path.write_text(PARAMS_HELPER_TEMPLATE)

        cargo_settings = (spec_settings or {}).get("cargo-test", {})
        run_env = {"VALIDATION_PARAMS": str(params_path)}
        for k, v in cargo_settings.get("env", {}).items():
            run_env[str(k)] = str(v)

        try:
            run_result = run(
                RustRunConfig(
                    test_file=script_path,
                    repo_dir=repo_dir,
                    crate=cargo_package,
                    workspace_dir=story.get("cargo_module_dir", ""),
                    timeout=timeout,
                    env=run_env,
                    command=cargo_settings.get("command", "cargo test"),
                    extra_args=cargo_settings.get("extra_args", ""),
                    extra_files=[helper_path],
                )
            )
        finally:
            helper_path.unlink(missing_ok=True)

        result.cases = _map_cargo_cases(run_result, len(test_cases))
        return result


def _map_cargo_cases(run_result, expected_count: int):
    """Map cargo output to per-case results.

    Rust's stable libtest has no runtime subtests (Go's ``t.Run`` / mix's
    generated ``test case_N``) and no parametrization (pytest's
    ``ids=[case_N]``), so the framework-recommended validation shape — the one
    the helper (``get_validation_test_cases``) and the validation prompt both
    illustrate — is a SINGLE looping ``#[test]`` function that walks every case
    and panics on the first failing assertion. That function surfaces in cargo
    output as exactly one ``test <fn_name> ... ok|FAILED`` line whose name never
    contains ``case_N`` (the ``case_i`` label lives only in the loop's panic
    messages). The generic ``map_run_result_to_cases`` matcher keys on
    ``case_N`` test names, so on its own it reports every case as "not found"
    even for a perfectly correct solution — zeroing ``validation_score``.

    So:
    1. If the binary DOES expose ``case_N``-named tests (a task that wrote one
       ``#[test]`` fn per case, or a future macro helper), defer to the generic
       per-case matcher — fully backward compatible.
    2. Otherwise, treat the single looping function's verdict as the verdict for
       ALL cases: ``ok`` => every case's assertion held; ``FAILED`` => at least
       one case tripped (Rust panics on the first, so the failing index is not
       individually attributable). This mirrors ``pytest_driver``'s
       single-test fallback, generalized to N cases because one loop covers
       them all.
    3. If no scorable test ran at all (compile error, timeout, empty output),
       defer to the generic matcher, which reports "not found" with the exit
       code and raw output — the correct signal for an INVALID/failed run.
    """
    has_case_names = any(f"case_{i}" in t.name for i in range(expected_count) for t in run_result.tests)
    if has_case_names:
        return map_run_result_to_cases(run_result, expected_count, "cargo test")

    real_tests = [t for t in run_result.tests if t.name not in ("build_error", "timeout")]
    if not real_tests:
        # Compile error / timeout / empty output — nothing scorable ran.
        return map_run_result_to_cases(run_result, expected_count, "cargo test")

    if all(t.passed for t in real_tests):
        return [CaseResult(case_index=i, passed=True, ran=Execution.yes) for i in range(expected_count)]

    detail = "; ".join(t.detail for t in real_tests if not t.passed and t.detail) or "cargo test reported failure"
    return [
        CaseResult(
            case_index=i,
            passed=False,
            reason=f"Case {i}: {detail}",
            stdout=run_result.raw_stdout[-500:],
            stderr=run_result.raw_stderr[-500:],
            ran=Execution.yes,
        )
        for i in range(expected_count)
    ]
